/**
 * Build-time plumbing that is not part of the app's source:
 *
 *  1. A Content-Security-Policy <meta> on every page (production only). The
 *     policy sets `connect-src 'none'`, so scripts on these pages cannot make
 *     fetch/XHR/WebSocket/beacon requests at all: the privacy claim is enforced
 *     by the browser, not just promised. Inline scripts are allowed by hash.
 *  2. Preload tags for the two display faces (their hashed names are only
 *     known at build time).
 *  3. `_headers` (Netlify / Cloudflare Pages format) with the same policy as real HTTP headers plus
 *     the ones a <meta> cannot carry (`frame-ancestors`), `nosniff` and a no-referrer policy.
 *  4. `app/sw.js`: a small hand-written service worker whose precache list is
 *     generated from the app page's real module graph, so the app works fully
 *     offline after the first load. It touches same-origin GET requests only.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, posix, relative, resolve } from 'node:path';
import type { Plugin } from 'vite';

interface OutputChunk {
  type: 'chunk';
  fileName: string;
  code: string;
  imports: string[];
  dynamicImports: string[];
  viteMetadata?: { importedCss?: Set<string>; importedAssets?: Set<string> };
}
interface OutputAsset {
  type: 'asset';
  fileName: string;
  source: string | Uint8Array;
}
type OutputBundle = Record<string, OutputChunk | OutputAsset>;

// HTML parsers normalise CRLF to LF inside script text, and CSP hashes the normalised text.
const sha256 = (s: string): string =>
  createHash('sha256').update(s.split('\r\n').join('\n').split('\r').join('\n')).digest('base64');

function csp(inlineScripts: string[], page: 'landing' | 'app'): string {
  const hashes = inlineScripts.map((s) => `'sha256-${sha256(s)}'`).join(' ');
  const directives = [
    "default-src 'none'",
    `script-src 'self' ${hashes}`.trim(),
    "style-src 'self'",
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    ...(page === 'app' ? ["manifest-src 'self'", "worker-src 'self'"] : []),
  ];
  return directives.join('; ');
}

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

const SW_TEMPLATE = `/* Readback web app service worker. Generated by scripts/pwa-plugin.ts. */
const CACHE = 'readback-app-__VERSION__';
const PRECACHE = __LIST__;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((k) => k.startsWith('readback-app-') && k !== CACHE).map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

// Same-origin GET only. Everything the app needs is precached, so after the first
// load nothing here ever goes to the network; a miss falls through to the browser.
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      // ignoreVary: hosts often send "Vary: Origin", and module scripts send an Origin
      // header that the precache requests did not, which would turn every lookup into a miss.
      const hit = await cache.match(request, { ignoreSearch: true, ignoreVary: true });
      if (hit) return hit;
      if (request.mode === 'navigate') {
        const shell = await cache.match(new URL('./', self.location.href).href);
        if (shell) return shell;
      }
      return fetch(request);
    }),
  );
});
`;

/** Headers for hosts that read a `_headers` file. `frame-ancestors` is ignored in a <meta> CSP. */
function headersFile(policies: Partial<Record<'landing' | 'app', string>>): string {
  const common = [
    'X-Content-Type-Options: nosniff',
    'Referrer-Policy: no-referrer',
    'Cross-Origin-Opener-Policy: same-origin',
    'Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()',
  ];
  const block = (paths: string[], policy: string | undefined): string[] =>
    policy
      ? paths.flatMap((path) => [
          path,
          `  Content-Security-Policy: ${policy}; frame-ancestors 'none'`,
          ...common.map((h) => `  ${h}`),
          '',
        ])
      : [];
  return [
    '# Generated by scripts/pwa-plugin.ts. Same policy as the <meta> tag on each page.',
    ...block(['/', '/index.html'], policies.landing),
    ...block(['/app', '/app/', '/app/*'], policies.app),
  ].join('\n');
}

export function pwaPlugin(): Plugin {
  let outDir = '';
  let isBuild = false;
  const policies: Partial<Record<'landing' | 'app', string>> = {};
  return {
    name: 'readback-site:pwa',
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
      isBuild = config.command === 'build';
    },
    transformIndexHtml: {
      order: 'post',
      handler(html, ctx) {
        if (!isBuild) return html;
        const page = ctx.filename.replaceAll('\\', '/').endsWith('/app/index.html')
          ? 'app'
          : 'landing';
        const inline = [...html.matchAll(/<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(
          (m) => m[1] ?? '',
        );
        const prefix = page === 'app' ? '../' : './';
        const fonts: string[] = [];
        if (ctx.bundle) {
          for (const file of Object.keys(ctx.bundle)) {
            const faces =
              page === 'app' ? /(hubot-sans|mona-sans|geist-mono)/ : /(hubot-sans|mona-sans)/;
            if (faces.test(file) && file.endsWith('.woff2')) fonts.push(file);
          }
        }
        const preloads = fonts
          .map(
            (f) =>
              `<link rel="preload" as="font" type="font/woff2" href="${prefix}${f}" crossorigin />`,
          )
          .join('\n    ');
        policies[page] = csp(inline, page);
        const meta = `<meta http-equiv="Content-Security-Policy" content="${policies[page]}" />`;
        return html
          .replace('<meta charset="utf-8" />', (m) => `${m}\n    ${meta}`)
          .replace('</head>', `    ${preloads}\n  </head>`);
      },
    },
    writeBundle(_options, bundle: OutputBundle) {
      if (isBuild && (policies.landing ?? policies.app)) {
        writeFileSync(join(outDir, '_headers'), headersFile(policies));
      }
      const appHtml = bundle['app/index.html'];
      if (!appHtml || appHtml.type !== 'asset') return;
      const html = String(appHtml.source);
      const wanted = new Set<string>(['app/index.html']);

      const chunkByFile = new Map<string, OutputChunk>();
      for (const item of Object.values(bundle))
        if (item.type === 'chunk') chunkByFile.set(item.fileName, item);

      const addChunk = (file: string): void => {
        if (wanted.has(file)) return;
        wanted.add(file);
        const chunk = chunkByFile.get(file);
        if (!chunk) return;
        for (const dep of [...chunk.imports, ...chunk.dynamicImports]) addChunk(dep);
        for (const css of chunk.viteMetadata?.importedCss ?? []) wanted.add(css);
        for (const asset of chunk.viteMetadata?.importedAssets ?? []) wanted.add(asset);
      };

      for (const m of html.matchAll(/(?:src|href)="([^"]+)"/g)) {
        const ref = m[1] ?? '';
        if (/^(https?:)?\/\//.test(ref) || ref.startsWith('data:') || ref.startsWith('#')) continue;
        const file = posix.normalize(posix.join('app', ref));
        if (chunkByFile.has(file)) addChunk(file);
        else if (bundle[file]) wanted.add(file);
      }
      // Fonts are referenced from CSS url(), not imported by any chunk.
      for (const file of [...wanted]) {
        if (!file.endsWith('.css')) continue;
        const css = bundle[file];
        if (css?.type !== 'asset') continue;
        for (const u of String(css.source).matchAll(/url\(([^)]+)\)/g)) {
          const ref = (u[1] ?? '').replace(/["']/g, '');
          if (ref.startsWith('data:')) continue;
          const target = posix.normalize(posix.join(posix.dirname(file), ref));
          if (bundle[target]) wanted.add(target);
        }
      }

      // Public files the app page needs (icons, manifest). Present on disk after the copy.
      const extra: string[] = [];
      for (const f of walk(outDir)) {
        const rel = relative(outDir, f).replaceAll('\\', '/');
        if (rel.startsWith('app/icons/') || rel === 'app/manifest.webmanifest') extra.push(rel);
        if (rel === 'favicon.svg' || rel === 'apple-touch-icon.png') extra.push(rel);
      }

      const files = [...wanted, ...extra].filter((f) => f !== 'app/index.html').sort();
      const hash = createHash('sha256');
      for (const f of files) {
        const item = bundle[f];
        if (item?.type === 'chunk') hash.update(item.code);
        else if (item?.type === 'asset') hash.update(item.source);
        else hash.update(readFileSync(join(outDir, f)));
      }
      hash.update(html);
      const version = hash.digest('hex').slice(0, 12);

      const rels = ['./', ...['app/index.html', ...files].map((f) => posix.relative('app', f))];
      const sw = SW_TEMPLATE.replace('__VERSION__', version).replace(
        '__LIST__',
        JSON.stringify(rels, null, 2),
      );
      writeFileSync(join(outDir, 'app', 'sw.js'), sw);
    },
  };
}
