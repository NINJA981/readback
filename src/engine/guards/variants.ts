const index = new Map<string, Set<string>>();
for (const group of VARIANT_GROUPS) {
  for (const name of group) {
    const peers = index.get(name) ?? new Set<string>();
    for (const other of group) if (other !== name) peers.add(other);
    index.set(name, peers);
  }
}

/** True when `a` and `b` (folded) are different spellings in the same group. */
export function isVariantPair(a: string, b: string): boolean {
  return a !== b && (index.get(a)?.has(b) ?? false);
}

/** Number of unordered pairs the table encodes (SPEC: about 120). */
export function variantPairCount(): number {
  let pairs = 0;
  for (const group of VARIANT_GROUPS) pairs += (group.length * (group.length - 1)) / 2;
  return pairs;
}
